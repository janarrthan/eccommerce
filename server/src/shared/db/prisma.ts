import { PrismaPg } from "@prisma/adapter-pg";

import { PrismaClient } from "../../generated/prisma/client.js";
import { env } from "../config/env.js";
import { requireTestWorkerDatabaseUrl } from "../config/test-database.js";

function getDatabaseUrl(): URL {
  if (env.NODE_ENV === "test" || process.env.VITEST === "true") {
    return requireTestWorkerDatabaseUrl(process.env);
  }

  if (!env.DATABASE_URL) {
    throw new Error("DATABASE_URL is required outside tests.");
  }

  return new URL(env.DATABASE_URL);
}

const databaseUrl = getDatabaseUrl();
const databaseSchema = databaseUrl.searchParams.get("schema") ?? "public";
const adapter = new PrismaPg(
  {
    connectionString: databaseUrl.toString(),
    // The schema option below controls SQL generated by Prisma. Set PostgreSQL's search path as well
    // so raw SQL without a schema name uses only this worker's schema and cannot fall back to public.
    ...(env.NODE_ENV === "test" ? { options: `-c search_path=${databaseSchema}` } : {}),
  },
  // Use this schema for SQL generated by Prisma. The search path above handles raw SQL separately.
  { schema: databaseSchema },
);

export const prisma = new PrismaClient({
  adapter,
});
